#      Internet = On.
#   2. Optional, for the preferred base model (FunctionGemma 270M): accept its licence at
#      huggingface.co/google/functiongemma-270m-it, make a read token on Hugging Face, and add it
#      in Kaggle under Add-ons -> Secrets as  HF_TOKEN.  Without it the cell falls back to an
#      open copy of the same model, or to Qwen2.5-0.5B-Instruct.
#   3. Paste this whole file into one cell and run it (about 30-50 minutes on a T4).
#   4. Output panel -> download  hth_assistant_model.zip.  On the shop PC:
#      Settings -> Assistant -> Install model..., pick the zip.
#
# Privacy: no shop data is used or uploaded.  The questions are generated from the app's own
# templates (embedded below) with <C1> / <I1> standing in for every customer and item name.
