END = "<end_of_turn>"


def encode(e):
    p = tok(data.prompt(e.text), add_special_tokens=True)["input_ids"]
    c = tok(data.target(e.intent, e.args) + END, add_special_tokens=False)["input_ids"]
    ids = (p + c)[:MAX_LEN]
    labels = ([-100] * len(p) + c)[:MAX_LEN]
    return ids, labels


