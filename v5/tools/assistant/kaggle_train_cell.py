def loss_on_answer(ids, mask, labels):
    """Run the decoder, then the (huge-vocabulary) output layer only where the answer is."""
    target = labels[:, 1:]
    keep = target != -100
    with torch.autocast(device_type="cuda", dtype=torch.bfloat16, enabled=use_bf16):
        hidden = inner.model(input_ids=ids, attention_mask=mask).last_hidden_state
        logits = inner.lm_head(hidden[:, :-1][keep])
    logits = logits.float()
    if softcap:
        logits = torch.tanh(logits / softcap) * softcap
    return F.cross_entropy(logits, target[keep])


def batches(rows, size, shuffle_seed):
    order = list(range(len(rows)))
    random.Random(shuffle_seed).shuffle(order)
    for k in range(0, len(order), size):
        chunk = [rows[i] for i in order[k : k + size]]
        width = max(len(i) for i, _ in chunk)
        ids = torch.full((len(chunk), width), tok.pad_token_id, dtype=torch.long)
        lab = torch.full((len(chunk), width), -100, dtype=torch.long)
        mask = torch.zeros((len(chunk), width), dtype=torch.long)
        for r, (i, lbl) in enumerate(chunk):
            ids[r, : len(i)] = torch.tensor(i)
            lab[r, : len(lbl)] = torch.tensor(lbl)
            mask[r, : len(i)] = 1
        yield ids.to(device), mask.to(device), lab.to(device)


