"""Hindi copies of customer and item names (``name_hi`` / ``details_hi`` columns).

English stays the record of truth - ledgers, bills, search and exports to v4 all use it.
The Hindi copy is generated by :mod:`hth.i18n.translit`; once someone corrects it by hand
(``hi_manual = 1``) it is never regenerated.
"""

from __future__ import annotations

from dataclasses import dataclass

from hth.db.connection import Database
from hth.domain.constants import AuditCode
from hth.i18n.translit import to_hindi
from hth.services.accounts import ValidationError
from hth.services.audit import AuditService


@dataclass(frozen=True)
class HindiRow:
    kind: str  # customer | item
    id: int
    english: str
    hindi: str
    details: str
    details_hi: str
    manual: bool


class HindiNamesService:
    def __init__(self, db: Database):
        self.db = db
        self.audit = AuditService(db)

    def _has_columns(self) -> bool:
        cols = {r["name"] for r in self.db.fetchall("PRAGMA table_info(customers)")}
        return "name_hi" in cols

    # Bulk -------------------------------------------------------------------------------
    def fill_missing(self, username: str = "system", regenerate: bool = False) -> tuple[int, int]:
        """Give every customer and item without a Hindi copy one.  ``regenerate`` redoes all
        automatic copies (after the word list improved); hand-corrected ones are kept.
        Returns (customers, items) written."""
        if not self._has_columns():
            return 0, 0
        cond = (
            "hi_manual = 0"
            if regenerate
            # blank details have a blank copy: not "missing" (else every start would redo them)
            else "hi_manual = 0 AND (name_hi = '' OR (details_hi = '' AND TRIM(other_details) != ''))"
        )
        n_c = n_i = 0
        with self.db.connect():
            for r in self.db.fetchall(f"SELECT id, name, other_details FROM customers WHERE {cond}"):
                self.db.execute(
                    "UPDATE customers SET name_hi = ?, details_hi = ? WHERE id = ?",
                    (to_hindi(r["name"]), to_hindi(r["other_details"]), r["id"]),
                )
                n_c += 1
            item_cond = "hi_manual = 0" if regenerate else "hi_manual = 0 AND name_hi = ''"
            for r in self.db.fetchall(f"SELECT id, name FROM items WHERE {item_cond}"):
                self.db.execute("UPDATE items SET name_hi = ? WHERE id = ?", (to_hindi(r["name"], item=True), r["id"]))
                n_i += 1
            if n_c or n_i:
                self.audit.log(AuditCode.MODIFY, f"Hindi names generated: {n_c} customers, {n_i} items", username)
        return n_c, n_i

    # One record -------------------------------------------------------------------------
    def set_customer(self, customer_id: int, name_hi: str, details_hi: str, username: str) -> None:
        name_hi, details_hi = (name_hi or "").strip(), (details_hi or "").strip()
        if not name_hi:
            raise ValidationError("Hindi name is required (or reset it to automatic).")
        with self.db.connect():
            self.db.execute(
                "UPDATE customers SET name_hi = ?, details_hi = ?, hi_manual = 1 WHERE id = ?",
                (name_hi, details_hi, customer_id),
            )
            self.audit.log(AuditCode.MODIFY, f"customer {customer_id} Hindi name -> {name_hi}", username)

    def set_item(self, item_id: int, name_hi: str, username: str) -> None:
        name_hi = (name_hi or "").strip()
        if not name_hi:
            raise ValidationError("Hindi name is required (or reset it to automatic).")
        with self.db.connect():
            self.db.execute("UPDATE items SET name_hi = ?, hi_manual = 1 WHERE id = ?", (name_hi, item_id))
            self.audit.log(AuditCode.MODIFY, f"item {item_id} Hindi name -> {name_hi}", username)

    def reset(self, kind: str, record_id: int, username: str) -> None:
        """Back to the automatic Hindi copy."""
        with self.db.connect():
            if kind == "customer":
                r = self.db.fetchone("SELECT name, other_details FROM customers WHERE id = ?", (record_id,))
                if r:
                    self.db.execute(
                        "UPDATE customers SET name_hi = ?, details_hi = ?, hi_manual = 0 WHERE id = ?",
                        (to_hindi(r["name"]), to_hindi(r["other_details"]), record_id),
                    )
            else:
                r = self.db.fetchone("SELECT name FROM items WHERE id = ?", (record_id,))
                if r:
                    self.db.execute(
                        "UPDATE items SET name_hi = ?, hi_manual = 0 WHERE id = ?",
                        (to_hindi(r["name"], item=True), record_id),
                    )
            self.audit.log(AuditCode.MODIFY, f"{kind} {record_id} Hindi name reset to automatic", username)

    # Reading ----------------------------------------------------------------------------
    def rows(self) -> list[HindiRow]:
        if not self._has_columns():
            return []
        out = [
            HindiRow(
                "customer", r["id"], r["name"], r["name_hi"], r["other_details"], r["details_hi"], bool(r["hi_manual"])
            )
            for r in self.db.fetchall(
                "SELECT id, name, name_hi, other_details, details_hi, hi_manual FROM customers ORDER BY id"
            )
        ]
        out += [
            HindiRow("item", r["id"], r["name"], r["name_hi"], "", "", bool(r["hi_manual"]))
            for r in self.db.fetchall("SELECT id, name, name_hi, hi_manual FROM items ORDER BY id")
        ]
        return out

    def lookup(self) -> tuple[dict[str, str], dict[str, str]]:
        """(names, details): English text -> Hindi copy, for :func:`hth.i18n.set_names`."""
        names: dict[str, str] = {}
        details: dict[str, str] = {}
        for r in self.rows():
            if r.hindi:
                names.setdefault(r.english, r.hindi)
            if r.details_hi:
                details.setdefault(r.details, r.details_hi)
        if self._has_columns():  # customer labels in pickers: "6 RAMNIWAS GADA GOPAL 7206525141"
            for r in self.db.fetchall(
                "SELECT id, name, name_hi, other_details, details_hi FROM customers WHERE name_hi != ''"
            ):
                names.setdefault(
                    f"{r['id']} {r['name']} {r['other_details']}".strip(),
                    f"{r['id']} {r['name_hi']} {r['details_hi'] or r['other_details']}".strip(),
                )
        if self._has_columns():  # item labels as shown in pickers and ledger text: "4 CYPRA PLUS NA"
            for r in self.db.fetchall("SELECT id, name, name_hi, batch FROM items WHERE name_hi != ''"):
                names.setdefault(
                    f"{r['id']} {r['name']} {r['batch']}".strip(), f"{r['id']} {r['name_hi']} {r['batch']}".strip()
                )
        return names, details
